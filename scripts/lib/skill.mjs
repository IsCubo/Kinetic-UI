// Shared logic for validating an Agent Skill and generating its keyword index.
// Zero dependencies: runs on any Node.js >= 18.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

export const INDEX_FILE = 'INDEX.md';

// Agent Skills spec limits (https://agentskills.io/specification).
const NAME_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const MAX_NAME = 64;
const MAX_DESCRIPTION = 1024;
const STYLE_DESCRIPTION = 250; // stricter house style; warning only
const MAX_BODY_LINES = 500;
const MAX_BODY_TOKENS = 1000; // estimated as characters / 4

// Sections every file in these folders must contain (exact level-2 headings).
export const REQUIRED_SECTIONS = {
  'references/effects/': ['## Reduced motion', '## Low-end fallback'],
  'references/components/': ['## Reduced motion', '## Low-end fallback'],
  'references/styles/': ['## Reduced motion', '## Low-end fallback'],
};

const INDEXED_ROOTS = ['references', 'assets'];
const INDEXED_EXT = new Set(['.md', '.css', '.js', '.mjs', '.ts', '.tsx', '.jsx', '.html', '.json', '.dart', '.swift', '.kt']);
const JS_EXT = new Set(['.js', '.mjs']);
const HEADER_LINES = 8;

// Parses the small YAML subset used by SKILL.md frontmatter: `key: value` pairs and one nesting level.
export function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return null;
  const data = {};
  let parent = null;
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const kv = line.match(/^(\s*)([A-Za-z0-9_.-]+):\s*(.*)$/);
    if (!kv) continue;
    const [, indent, key, raw] = kv;
    const value = raw.replace(/^(["'])(.*)\1$/, '$2');
    if (indent.length === 0) {
      if (raw === '') { data[key] = {}; parent = key; } else { data[key] = value; parent = null; }
    } else if (parent) {
      data[parent][key] = value;
    }
  }
  return { data, body: text.slice(m[0].length) };
}

// Lists files under `dir` (recursive), relative to `root`, skipping hidden entries. Sorted for determinism.
function walk(root, dir = root) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(root, full));
    else out.push(path.relative(root, full).split(path.sep).join('/'));
  }
  return out.sort();
}

export function indexedFiles(skillDir) {
  return INDEXED_ROOTS.flatMap((r) => walk(skillDir, path.join(skillDir, r)))
    .filter((rel) => INDEXED_EXT.has(path.extname(rel)) && !/^(LICENSE|README)/i.test(path.basename(rel)));
}

function clean(value) {
  return value.replace(/\s*(\*\/|-->)\s*$/, '').replace(/^["']|["'],?\s*$/g, '').trim();
}

// Reads the `Keywords:` and `Summary:` header lines from the first lines of any supported file type.
export function readHeader(text) {
  const head = text.split(/\r?\n/).slice(0, HEADER_LINES);
  const find = (label) => {
    const re = new RegExp(`\\b\\$?${label}"?\\s*:\\s*(.+)$`, 'i');
    for (const line of head) {
      const m = line.match(re);
      if (m) return clean(m[1]);
    }
    return null;
  };
  return { keywords: find('keywords'), summary: find('summary') };
}

const escapeCell = (s) => s.replace(/\|/g, '\\|');

// Generates INDEX.md deterministically from every indexed file's header.
export function buildIndex(skillDir) {
  const name = path.basename(path.resolve(skillDir));
  const groups = new Map();
  for (const rel of indexedFiles(skillDir)) {
    const { keywords, summary } = readHeader(fs.readFileSync(path.join(skillDir, rel), 'utf8'));
    const group = path.posix.dirname(rel);
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(`| \`${rel}\` | ${escapeCell(summary ?? '')} | ${escapeCell(keywords ?? '')} |`);
  }
  const lines = [
    `# ${name} index`,
    '',
    '<!-- Generated by scripts/build-index.mjs. Do not edit by hand. -->',
    '',
    'Keyword catalog of every reference and asset. Search this file for a keyword, then open only the listed path (relative to the skill root).',
    '',
  ];
  for (const group of [...groups.keys()].sort()) {
    lines.push(`## ${group}`, '', '| Path | Summary | Keywords |', '| --- | --- | --- |', ...groups.get(group), '');
  }
  return lines.join('\n');
}

// Collects path references (markdown links and code spans) that point inside the skill.
function referencedPaths(text) {
  const found = new Set();
  const local = /^(references|assets)\/|^(SKILL|INDEX)\.md$/;
  for (const m of text.matchAll(/\]\(([^)\s]+)\)/g)) found.add(m[1]);
  for (const m of text.matchAll(/`([^`\s]+)`/g)) found.add(m[1]);
  return [...found].map((p) => p.split('#')[0]).filter((p) => p && local.test(p));
}

export function validate(skillDir) {
  const errors = [];
  const warnings = [];
  const err = (rule, file, msg) => errors.push(`ERROR [${rule}] ${file}: ${msg}`);
  const dirName = path.basename(path.resolve(skillDir));
  const skillPath = path.join(skillDir, 'SKILL.md');

  if (!fs.existsSync(skillPath)) {
    err('frontmatter', 'SKILL.md', 'file not found');
    return { errors, warnings, checked: 0 };
  }
  const skillText = fs.readFileSync(skillPath, 'utf8');
  const fm = parseFrontmatter(skillText);
  if (!fm) {
    err('frontmatter', 'SKILL.md', 'missing YAML frontmatter');
  } else {
    const { name, description, license, metadata } = fm.data;
    if (!name || !NAME_RE.test(name) || name.length > MAX_NAME) err('frontmatter', 'SKILL.md', `invalid name "${name ?? ''}"`);
    else if (name !== dirName) err('frontmatter', 'SKILL.md', `name "${name}" must match directory "${dirName}"`);
    if (!description) err('frontmatter', 'SKILL.md', 'description is required');
    else if (description.length > MAX_DESCRIPTION) err('frontmatter', 'SKILL.md', `description is ${description.length} chars (max ${MAX_DESCRIPTION})`);
    else if (description.length > STYLE_DESCRIPTION) warnings.push(`WARN [frontmatter] SKILL.md: description is ${description.length} chars (house style max ${STYLE_DESCRIPTION})`);
    if (!license) err('frontmatter', 'SKILL.md', 'license is required');
    if (!metadata || typeof metadata !== 'object' || !metadata.author || !metadata.version) {
      err('frontmatter', 'SKILL.md', 'metadata.author and metadata.version are required');
    }
    const bodyLines = fm.body.split(/\r?\n/).length;
    const bodyTokens = Math.ceil(fm.body.length / 4);
    if (bodyLines >= MAX_BODY_LINES) err('body-size', 'SKILL.md', `body has ${bodyLines} lines (max ${MAX_BODY_LINES - 1})`);
    if (bodyTokens > MAX_BODY_TOKENS) err('body-size', 'SKILL.md', `body is ~${bodyTokens} tokens (max ${MAX_BODY_TOKENS})`);
  }

  const files = indexedFiles(skillDir);
  for (const rel of files) {
    const text = fs.readFileSync(path.join(skillDir, rel), 'utf8');
    const { keywords, summary } = readHeader(text);
    if (!keywords) err('header', rel, `missing "Keywords:" line in the first ${HEADER_LINES} lines`);
    if (!summary) err('header', rel, `missing "Summary:" line in the first ${HEADER_LINES} lines`);
    for (const [prefix, sections] of Object.entries(REQUIRED_SECTIONS)) {
      if (!rel.startsWith(prefix) || !rel.endsWith('.md')) continue;
      for (const section of sections) {
        const re = new RegExp(`^${section.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$`, 'm');
        if (!re.test(text)) err('required-sections', rel, `missing section "${section}"`);
      }
    }
    if (JS_EXT.has(path.extname(rel))) {
      // Parse as an ES module via stdin: `node --check file.js` silently passes ESM syntax errors in .js files (Node 22).
      const r = spawnSync(process.execPath, ['--input-type=module', '--check'], { input: text, encoding: 'utf8' });
      if (r.status !== 0) err('js-syntax', rel, (r.stderr.split('\n').find((l) => /Error/.test(l)) ?? 'syntax error').trim());
    }
  }

  const mdFiles = ['SKILL.md', ...(fs.existsSync(path.join(skillDir, INDEX_FILE)) ? [INDEX_FILE] : []), ...files.filter((f) => f.endsWith('.md'))];
  for (const rel of mdFiles) {
    for (const target of referencedPaths(fs.readFileSync(path.join(skillDir, rel), 'utf8'))) {
      if (!fs.existsSync(path.join(skillDir, target))) err('links', rel, `references missing path "${target}" (paths are relative to the skill root)`);
    }
  }

  const indexPath = path.join(skillDir, INDEX_FILE);
  const expected = buildIndex(skillDir);
  if (!fs.existsSync(indexPath)) err('index-fresh', INDEX_FILE, 'not found; run scripts/build-index.mjs');
  else if (fs.readFileSync(indexPath, 'utf8') !== expected) err('index-fresh', INDEX_FILE, 'stale; run scripts/build-index.mjs');

  return { errors, warnings, checked: files.length + 1 };
}
